#!/usr/bin/env python3
"""Emit src/wbc_net.h - the decoded TransformIT iAES2 decrypt network.

The network was recovered by emulating TFIT_op_iAES2 (see extract.py) and is
validated against the real object code for all 101 key indices and random
inputs.  It contains no key material and no Arxan tables: only the *shape* of
the computation (which state slot feeds which, which table slot, which byte).
The 84 tables and the 101 key blobs are supplied at run time by the user.
"""
import json, os, struct, sys

HERE = os.environ.get("WBC_DIR", "/tmp/opencode/arxan")
OUT  = os.environ.get("WBC_OUT", "src/wbc_net.h")


def rebuild(e):
    if isinstance(e, list):
        return tuple(rebuild(x) for x in e)
    return e


def main():
    d = json.load(open(os.environ.get("WBC_NET", "%s/net.json" % HERE)))
    ops = [(a, rebuild(e)) for a, e in d["ops"]]
    outmap = {o: rebuild(e) for o, e in d["out"]}

    # collect every state slot the network touches
    slots = {}

    def slot(a):
        if a not in slots:
            slots[a] = len(slots)
        return slots[a]

    steps = []
    for a, e in ops:
        assert e[0] == "xor" and len(e) == 3, e
        # one operand is the table lookup, the other the accumulator
        if e[1][0] == "t":
            tab, acc = e[1], e[2]
        elif e[2][0] == "t":
            tab, acc = e[2], e[1]
        else:
            raise SystemExit("no table lookup in %r" % (e,))
        tbl, idxe = tab[1], tab[2]
        # accumulator: state slot or key word
        if acc[0] == "ld":
            src, keyw = slot(acc[1]), -1
        elif acc[0] == "k":
            src, keyw = -1, acc[1]
        else:
            raise SystemExit("bad accumulator %r" % (acc,))
        # index expression
        isin, sh, idxs = 0, 0, 0
        if idxe[0] == "in":
            isin, idxs = 1, idxe[1]
        elif idxe[0] == "ld":
            idxs = slot(idxe[1])
        elif idxe[0] == "and" and idxe[2] == 255:
            inner = idxe[1]
            if inner[0] == "ld":
                idxs = slot(inner[1])
            elif inner[0] == "shr" and inner[2] in (8, 16, 24) and inner[1][0] == "ld":
                idxs, sh = slot(inner[1][1]), inner[2]
            else:
                raise SystemExit("bad index %r" % (idxe,))
        else:
            raise SystemExit("bad index %r" % (idxe,))
        steps.append((slot(a), src, keyw, idxs, tbl, isin, sh))

    outs = [slots[outmap[off][1]] if outmap[off][0] == "ld" else None
            for off in (0, 4, 8, 12)]
    assert all(o is not None for o in outs), outs

    with open(OUT, "w") as f:
        f.write("/* wbc_net.h - generated by tools/wbcextract/emit_c.py; do not edit.\n"
                " *\n"
                " * The TransformIT iAES2 block-decrypt network: 272 steps, each one\n"
                " *\n"
                " *     st[dst] = acc ^ table[tbl][ (x >> sh) & 0xff ]\n"
                " *\n"
                " * with acc taken from a state slot or from a key word and x from a\n"
                " * state slot or from an input byte.  Tables and key words come from\n"
                " * the user's own data at run time (see docs/KEYS.md); nothing in\n"
                " * this file is key material.\n"
                " */\n"
                "#ifndef WBC_NET_H\n#define WBC_NET_H\n\n")
        f.write("#define WBC_STEPS    %d\n" % len(steps))
        f.write("#define WBC_SLOTS    %d\n" % len(slots))
        f.write("#define WBC_TABLES   84\n")
        f.write("#define WBC_KEYWORDS 76\n\n")
        f.write("typedef struct {\n"
                "    unsigned short dst, src;   /* state slots                  */\n"
                "    short          keyw;       /* key word, or -1 for src slot  */\n"
                "    unsigned short idx;        /* state slot or input byte      */\n"
                "    unsigned char  tbl, isin, sh;\n"
                "} wbc_step;\n\n")
        f.write("static const wbc_step wbc_steps[WBC_STEPS] = {\n")
        for s in steps:
            f.write("    {%4d,%4d,%4d,%4d,%3d,%d,%2d},\n" % s)
        f.write("};\n\n")
        f.write("static const unsigned short wbc_output[4] = { %s };\n\n"
                % ", ".join(str(o) for o in outs))
        f.write("#endif /* WBC_NET_H */\n")
    print("wrote wbc_net.h: %d steps, %d slots, outputs %s" % (len(steps), len(slots), outs))


if __name__ == "__main__":
    main()
