    ok_perm = 0
    for off in sorted(NAMES):
        name = NAMES[off]
        T = struct.unpack("<256I", data[off:off+1024])
        # permutation test
        perm = len(set(T)) == 256
        ok_perm += perm
        if perm:
            print("%-11s injective" % name)
    print("injective tables: %d/84" % ok_perm)


