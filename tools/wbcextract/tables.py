def gm(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a = ((a << 1) ^ 0x1b) & 0xff if a & 0x80 else (a << 1) & 0xff
        b >>= 1
    return r


def col(s, coef):
    """MixColumns-style column vector for byte s with coefficient list."""
    return bytes([gm(s, coef[0]), gm(s, coef[1]), gm(s, coef[2]), gm(s, coef[3])])


